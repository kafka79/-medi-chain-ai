class NumberedCanvas(canvas.Canvas):
    """
    Two-pass canvas to dynamically compute total pages and render running footers and headers.
    """
    def __init__(self, *args, **kwargs):
        super().__init__(*args, **kwargs)
        self._saved_page_states = []

    def showPage(self):
        self._saved_page_states.append(dict(self.__dict__))
        self._startPage()

    def save(self):
        num_pages = len(self._saved_page_states)
        for state in self._saved_page_states:
            self.__dict__.update(state)
            self.draw_page_decorations(num_pages)
            super().showPage()
        super().save()

    def draw_page_decorations(self, page_count):
        self.saveState()
        self.setFont("Helvetica", 8)
        self.setFillColor(colors.HexColor('#64748B')) # light slate gray
        
        # Draw a footer separator line
        self.setStrokeColor(colors.HexColor('#E2E8F0'))
        self.setLineWidth(0.5)
        self.line(36, 45, 576, 45) # left margin 36 to right margin 576
        
        # Right-aligned page numbers
        page_text = f"Page {self._pageNumber} of {page_count}"
        self.drawRightString(576, 32, page_text)
        
        # Left-aligned confidentiality notice
        confidentiality_text = "CONFIDENTIAL CLINICAL REPORT — GENERATED BY MEDI CHAIN AI"
        self.drawString(36, 32, confidentiality_text)
        
        # If not the first page, draw a small running header
        if self._pageNumber > 1:
            self.setStrokeColor(colors.HexColor('#E2E8F0'))
            self.line(36, 756, 576, 756)
            self.drawString(36, 762, "MEdi Chain AI - Clinical Diagnostic Report")
            
        self.restoreState()


class ClinicalReportGenerator:
    """
    Generates professional PDF clinical reports for diagnostic results.
    Includes visual heatmaps, RAG citations, and uncertainty quantification.
    """
    def __init__(self, output_dir="outputs/reports"):
        self.output_dir = output_dir
        os.makedirs(self.output_dir, exist_ok=True)
        self.styles = getSampleStyleSheet()
        self.fhir_formatter = FHIRFormatter()
        self._configure_styles()

    def _configure_styles(self):
        # Premium color palette
        primary_color = colors.HexColor('#1E293B')   # Deep slate navy
        secondary_color = colors.HexColor('#0F766E') # Professional teal
        text_color = colors.HexColor('#334155')      # Neutral dark gray
        
        # Modify existing styles to use premium design tokens
        self.styles['Title'].textColor = primary_color
        self.styles['Title'].fontSize = 22
        self.styles['Title'].leading = 26
        self.styles['Title'].alignment = 0 # Left alignment
        self.styles['Title'].spaceAfter = 12
        
        self.styles['Heading2'].textColor = primary_color
        self.styles['Heading2'].fontSize = 13
        self.styles['Heading2'].leading = 16
        self.styles['Heading2'].spaceBefore = 10
        self.styles['Heading2'].spaceAfter = 6
        self.styles['Heading2'].keepWithNext = True

        self.styles['Heading3'].textColor = secondary_color
        self.styles['Heading3'].fontSize = 11
        self.styles['Heading3'].leading = 14
        self.styles['Heading3'].spaceBefore = 8
        self.styles['Heading3'].spaceAfter = 4
        self.styles['Heading3'].keepWithNext = True

        self.styles['Normal'].textColor = text_color
        self.styles['Normal'].fontSize = 9.5
        self.styles['Normal'].leading = 13.5
        
        self.styles['Italic'].textColor = colors.HexColor('#64748B')
        self.styles['Italic'].fontSize = 8.5
        self.styles['Italic'].leading = 11.5

    def generate_report(self, diagnosis_result, patient_metadata, heatmap_path, citations, output_filename=None):
        if not output_filename:
            pid = patient_metadata.get('patient_id', 'UNK')
            date_str = datetime.now().strftime("%Y%m%d_%H%M")
            output_filename = f"Report_{pid}_{date_str}.pdf"
        
        filepath = os.path.join(self.output_dir, output_filename)
        # Use 0.5 inch margins (36 points) for a cleaner grid alignment
        doc = SimpleDocTemplate(
            filepath, 
            pagesize=letter,
            leftMargin=36,
            rightMargin=36,
            topMargin=54,
            bottomMargin=54
        )
        elements = []

        # Header Title
        elements.append(Paragraph("MEdi Chain AI - Diagnostic Report", self.styles['Title']))
        elements.append(Paragraph(f"<b>Date:</b> {datetime.now().strftime('%B %d, %Y %H:%M')} &nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp; <b>Patient ID:</b> {patient_metadata.get('patient_id', 'UNK')}", self.styles['Normal']))
        elements.append(Spacer(1, 15))

        # Clinical Key Takeaways Section
        elements.append(Paragraph("Clinical Key Takeaways", self.styles['Heading2']))
        findings = diagnosis_result.get('top_finding', 'Inconclusive')
        confidence = diagnosis_result.get('confidence', 0.0)
        uncertainty = diagnosis_result.get('uncertainty_std', 0.0)
        
        # Color coding warning vs standard takeaways
        is_escalation = diagnosis_result.get('escalation_required', False)
        if is_escalation:
            takeaway_bg = colors.HexColor('#FEF2F2')
            takeaway_border = colors.HexColor('#FCA5A5')
        else:
            takeaway_bg = colors.HexColor('#F8FAFC')
            takeaway_border = colors.HexColor('#E2E8F0')
            
        takeaway_style = ParagraphStyle(
            'TakeawayPanel',
            parent=self.styles['Normal'],
            backColor=takeaway_bg,
            borderColor=takeaway_border,
            borderWidth=1,
            borderPadding=12,
            spaceAfter=15,
            leading=15
        )
        
        takeaway_text = f"<b>Primary Finding:</b> {findings}<br/>"
        takeaway_text += f"<b>Statistical Confidence:</b> {confidence:.1%} (±{uncertainty:.1%})<br/>"
        
        if is_escalation:
            takeaway_text += "<br/><font color='#B91C1C'><b>ACTION REQUIRED:</b> This case has been escalated for manual review due to insufficient automated evidence.</font>"
        else:
            takeaway_text += "<br/><b>Recommendation:</b> Correlate with clinical symptoms and history."

        elements.append(Paragraph(takeaway_text, takeaway_style))

        # Two-Column Table to place Heatmap next to Diagnostic Table (highly premium grid layout)
        table_data = []
        
        # Left side: Diagnostic Table
        left_flowables = []
        left_flowables.append(Paragraph("Differential Diagnosis Summary", self.styles['Heading3']))
        
        probs = diagnosis_result.get('probabilities', [])
        classes = ["Silicosis", "Pneumonia", "Tuberculosis", "Asbestosis", "Normal"]
        diff_data = [[
            Paragraph("<b>Condition</b>", self.styles['Normal']), 
            Paragraph("<b>Probability</b>", self.styles['Normal'])
        ]]
        
        cell_style = ParagraphStyle('TableCell', parent=self.styles['Normal'], fontSize=9)
        for i, p in enumerate(probs):
            if i < len(classes):
                is_top = (classes[i] == findings)
                weight_start = "<b>" if is_top else ""
                weight_end = "</b>" if is_top else ""
                diff_data.append([
                    Paragraph(f"{weight_start}{classes[i]}{weight_end}", cell_style),
                    Paragraph(f"{weight_start}{p:.1%}{weight_end}", cell_style)
                ])
                
        dt = Table(diff_data, colWidths=[150, 100])
        dt.setStyle(TableStyle([
            ('BACKGROUND', (0,0), (-1,0), colors.HexColor('#F1F5F9')),
            ('ALIGN', (0,0), (-1,-1), 'LEFT'),
            ('VALIGN', (0,0), (-1,-1), 'MIDDLE'),
            ('TOPPADDING', (0,0), (-1,-1), 5),
            ('BOTTOMPADDING', (0,0), (-1,-1), 5),
            ('LEFTPADDING', (0,0), (-1,-1), 8),
            ('RIGHTPADDING', (0,0), (-1,-1), 8),
            ('LINEBELOW', (0,0), (-1,0), 1.5, colors.HexColor('#CBD5E1')),
            ('LINEBELOW', (0,1), (-1,-1), 0.5, colors.HexColor('#E2E8F0')),
            ('GRID', (0,0), (-1,-1), 0.5, colors.HexColor('#E2E8F0')),
        ]))
        left_flowables.append(dt)
        left_flowables.append(Spacer(1, 10))

        # Right side: Visual Evidence
        right_flowables = []
        if os.path.exists(heatmap_path):
            right_flowables.append(Paragraph("Visual Evidence (Attention Mapping)", self.styles['Heading3']))
            img = Image(heatmap_path, width=180, height=180)
            right_flowables.append(img)
            right_flowables.append(Paragraph("<i>Highlighted regions indicate anatomical areas driving prediction.</i>", self.styles['Italic']))

        # Outer layout table to hold columns
        layout_table_data = [[left_flowables, right_flowables]]
        layout_table = Table(layout_table_data, colWidths=[270, 270])
        layout_table.setStyle(TableStyle([
            ('VALIGN', (0,0), (-1,-1), 'TOP'),
            ('LEFTPADDING', (0,0), (-1,-1), 0),
            ('RIGHTPADDING', (0,0), (-1,-1), 0),
            ('TOPPADDING', (0,0), (-1,-1), 0),
            ('BOTTOMPADDING', (0,0), (-1,-1), 0),
        ]))
        elements.append(layout_table)
        elements.append(Spacer(1, 15))

        # Appendix: Supporting Literature
        if citations:
            elements.append(Paragraph("Appendix: Supporting Literature", self.styles['Heading3']))
            cit_data = []
            for cit in citations:
                title = cit.get('title', 'Unknown Title')
                pmid = cit.get('pmid', 'N/A')
                cit_data.append([Paragraph(f"• <b>{title}</b> (PMID: {pmid})", self.styles['Normal'])])
            
            cit_table = Table(cit_data, colWidths=[540])
            cit_table.setStyle(TableStyle([
                ('VALIGN', (0,0), (-1,-1), 'MIDDLE'),
                ('BOTTOMPADDING', (0,0), (-1,-1), 3),
                ('TOPPADDING', (0,0), (-1,-1), 3),
                ('LEFTPADDING', (0,0), (-1,-1), 4),
            ]))
            elements.append(cit_table)
            elements.append(Paragraph("<i>Full snippets available in the digital FHIR sidecar.</i>", self.styles['Italic']))

        # Build PDF using NumberedCanvas subclass to get dynamic total pages
        doc.build(elements, canvasmaker=NumberedCanvas)
        fhir_path = self._write_fhir_sidecar(filepath, diagnosis_result, patient_metadata)
        print(f"Report generated successfully: {filepath}")
        return {"pdf_path": filepath, "fhir_path": fhir_path}

    def _write_fhir_sidecar(self, pdf_path, diagnosis_result, patient_metadata):
        probabilities = diagnosis_result.get('probabilities', [])
        classes = ["Silicosis", "Pneumonia", "Tuberculosis", "Asbestosis", "Normal"]
        differential = {
            classes[i]: probabilities[i]
            for i in range(min(len(classes), len(probabilities)))
        }
        diagnosis_data = {
            "patient_id": patient_metadata.get('patient_id', 'UNK'),
            "primary_finding": diagnosis_result.get('top_finding', 'Inconclusive'),
            "differential": differential,
            "confidence": diagnosis_result.get('confidence', 0.0),
            "report_path": pdf_path,
            "escalation_required": diagnosis_result.get('escalation_required', False),
        }
        report = self.fhir_formatter.create_diagnostic_report(diagnosis_data)
        fhir_path = os.path.splitext(pdf_path)[0] + ".fhir.json"
        with open(fhir_path, "w", encoding="utf-8") as handle:
            handle.write(self.fhir_formatter.to_json(report))
        return fhir_path

